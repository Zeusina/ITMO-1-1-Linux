#!/usr/bin/env bash

if (( $# != 3 )); then
 echo "Нужно передать ровно три аргумента: название файла, ключ -h или -t и количество строк для считывания"
 exit
fi

case $2 in
  "-h")
    head $1 -n $3 2>/dev/null
  ;;
  "-t")
    tail $1 -n $3 2>/dev/null
  ;;
  *)
    echo "Вы ввели неизвестный флаг, возможны -h и -t"
  ;;
esac
